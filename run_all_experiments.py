#!/usr/bin/env python3
"""Master runner: executes all 5 experiments and writes RESULTS.md."""

from __future__ import annotations

import os
import sys
import json
import time
from pathlib import Path

sys.path.insert(0, os.path.dirname(__file__))

RESULTS_DIR = "results"
os.makedirs(RESULTS_DIR, exist_ok=True)


def run_experiment(name: str, fn, *args, **kwargs):
    print(f"\n{'#'*70}")
    print(f"# Running {name}")
    print(f"{'#'*70}")
    t0 = time.time()
    result = fn(*args, **kwargs)
    elapsed = time.time() - t0
    print(f"\n  [{name}] completed in {elapsed:.1f}s")
    return result, elapsed


if __name__ == "__main__":
    from exp.exp1_local_global import run_exp1
    from exp.exp2_effective_reduction import run_exp2
    from exp.exp3_theorem_validation import run_exp3
    from exp.exp4_killed_law import run_exp4
    from exp.exp5_realization import run_exp5

    all_results = {}

    r1, t1 = run_experiment("Exp1 (alpha=0.2)", run_exp1, alpha=0.2)
    all_results["exp1_alpha_0.2"] = r1["summary"]

    r1b, t1b = run_experiment("Exp1 (alpha=0.4)", run_exp1, alpha=0.4)
    all_results["exp1_alpha_0.4"] = r1b["summary"]

    r2, t2 = run_experiment("Exp2", run_exp2)
    all_results["exp2"] = r2["summary"]

    r3, t3 = run_experiment("Exp3", run_exp3)
    all_results["exp3"] = r3["summary"]

    r4, t4 = run_experiment("Exp4", run_exp4)
    all_results["exp4"] = r4["summary"]

    r5, t5 = run_experiment("Exp5", run_exp5)
    all_results["exp5"] = r5["summary"]

    # ------------------------------------------------------------------ #
    # Write RESULTS.md
    # ------------------------------------------------------------------ #
    md_path = os.path.join(RESULTS_DIR, "RESULTS.md")
    with open(md_path, "w") as f:
        f.write("# Experiment Results\n\n")
        f.write("Generated by `run_all_experiments.py`.\n\n")

        f.write("## Experiment 1: Example 4.1 — Local vs Global Valuations\n\n")
        for key in ["exp1_alpha_0.2", "exp1_alpha_0.4"]:
            s = all_results[key]
            f.write(f"### alpha = {s['alpha']}\n")
            f.write(f"- T^{{abs}}_{{t0}} f_+(0) = {s['T_abs_t0_f_plus_0']:.6e}\n")
            f.write(f"- T^0_{{t0}} f_+(0)   = {s['T0_t0_f_plus_0']:.6f}\n")
            f.write(f"- Gap               = {s['gap_t0']:.6f}\n")
            f.write(f"- Strict separation = {s['strict_separation']}\n")
            f.write(f"- Generator residual (abs, finest h) = {s['gen_abs_max_res_finest_h']:.4e}\n")
            f.write(f"- Generator residual (T^0, finest h) = {s['gen_zero_max_res_finest_h']:.4e}\n\n")
        f.write("![Exp1 alpha=0.2](exp1_alpha0.2.png)\n\n")
        f.write("![Exp1 alpha=0.4](exp1_alpha0.4.png)\n\n")

        f.write("## Experiment 2: Example 4.2 — Effective Reduction G^downarrow\n\n")
        s2 = all_results["exp2"]
        f.write(f"- Max valuation error |V_t f - f(x+t)| = {s2['max_valuation_error']:.2e}\n")
        f.write(f"- G > G^downarrow at x=0 for p>0: {s2['strict_ineq_at_x0_p_pos']}\n")
        f.write(f"- G = G^downarrow at x=0 for p<=0: {s2['G_down_eq_G_at_x0_p_neg']}\n")
        f.write(f"- DQ convergence errors (finest h): {s2['dq_max_error_finest_h']}\n\n")
        f.write("![Exp2](exp2_effective_reduction.png)\n\n")

        f.write("## Experiment 3: HJB Theorem Validation\n\n")
        s3 = all_results["exp3"]
        for k, v in s3.items():
            f.write(f"- {k}: {v}\n")
        f.write("\n![Exp3](exp3_theorem_validation.png)\n\n")

        f.write("## Experiment 4: Killed-Law / Discounted-Pair Equivalence\n\n")
        s4 = all_results["exp4"]
        for k, v in s4.items():
            f.write(f"- {k}: {v}\n")
        f.write("\n![Exp4](exp4_killed_law.png)\n\n")

        f.write("## Experiment 5: Appendix-C Realization Pipeline\n\n")
        s5 = all_results["exp5"]
        for k, v in s5.items():
            f.write(f"- {k}: {v}\n")
        f.write("\n![Exp5](exp5_realization.png)\n\n")

        f.write("## Timing\n\n")
        f.write(f"| Experiment | Time (s) |\n|---|---|\n")
        for name, elapsed in [("Exp1 (0.2)", t1), ("Exp1 (0.4)", t1b),
                               ("Exp2", t2), ("Exp3", t3), ("Exp4", t4), ("Exp5", t5)]:
            f.write(f"| {name} | {elapsed:.1f} |\n")

    print(f"\nAll experiments done. Results written to {md_path}")
